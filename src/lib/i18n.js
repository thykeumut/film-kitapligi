export function t(lang, key) {
  const pack = I18N[lang] ?? I18N.tr;
  return pack[key] ?? I18N.tr[key] ?? key;
}

export function interpolate(str, vars) {
  return Object.keys(vars ?? {}).reduce(
    (acc, k) => acc.replace(new RegExp(`\\{${k}\\}`, 'g'), vars[k]),
    str,
  );
}
